    /**
     * Desa el proveïdor actual, ja sigui creant-lo o modificant-lo.
     *
     * @param evt esdeveniment del botó
     */
    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String name = txtName.getText();
        String password = new String(txtPassword.getPassword());
        String poblacio = txtPoblacio.getText();
        String email = txtEmail.getText();
        String telefon = txtTelefon.getText();

        ClientResponse<Void> response = suppliersService.saveSupplier(
                selectedOriginalName,
                name,
                password,
                poblacio,
                email,
                telefon
        );

        if (response.isSuccess()) {
            JOptionPane.showMessageDialog(
                    this,
                    response.getMessage(),
                    "Informació",
                    JOptionPane.INFORMATION_MESSAGE
            );
            loadSuppliers();
            clearForm();
            return;
        }

        JOptionPane.showMessageDialog(
                this,
                response.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE
        );
    }//GEN-LAST:event_btnSaveActionPerformed

    /**
     * Gestiona el botó "Elimina": elimina el proveïdor seleccionat.
     *
     * @param evt esdeveniment del botó
     */
    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String nameToDelete = selectedOriginalName;

        if (nameToDelete == null || nameToDelete.isBlank()) {
            nameToDelete = txtName.getText().trim();
        }

        if (nameToDelete.isBlank()) {
            JOptionPane.showMessageDialog(
                    this,
                    "Cal seleccionar un proveïdor.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        int option = JOptionPane.showConfirmDialog(
                this,
                "Vols eliminar el proveïdor \"" + nameToDelete + "\"?",
                "Confirmació",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE
        );

        if (option != JOptionPane.YES_OPTION) {
            return;
        }

        ClientResponse<Void> response = suppliersService.deleteSupplier(nameToDelete);

        if (response.isSuccess()) {
            JOptionPane.showMessageDialog(
                    this,
                    response.getMessage(),
                    "Informació",
                    JOptionPane.INFORMATION_MESSAGE
            );
            loadSuppliers();
            clearForm();
            return;
        }

        JOptionPane.showMessageDialog(
                this,
                response.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE
        );
    }//GEN-LAST:event_btnDeleteActionPerformed


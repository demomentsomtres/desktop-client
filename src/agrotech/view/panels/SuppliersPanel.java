    /**
     * Neteja el formulari i reinicia la selecció.
     */
    private void clearForm() {
        selectedOriginalName = null;
        txtName.setText("");
        txtPassword.setText("");
        txtPoblacio.setText("");
        txtEmail.setText("");
        txtTelefon.setText("");
        tblSuppliers.clearSelection();
        btnDelete.setEnabled(false);
        btnSave.setText("Crea");
        txtName.requestFocus();
    }

    /**
     * Carrega la llista de proveïdors a la taula.
     */
    private void loadSuppliers() {
        ClientResponse<List<ManagedSupplier>> response = suppliersService.getAllSuppliers();

        if (!response.isSuccess()) {
            JOptionPane.showMessageDialog(
                    this,
                    response.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        tableModel.setRowCount(0);

        for (ManagedSupplier supplier : response.getData()) {
            tableModel.addRow(new Object[]{
                supplier.getId(),
                supplier.getName(),
                supplier.getPoblacio(),
                supplier.getEmail(),
                supplier.getTelefon()
            });
        }
    }

    /**
     * Inicialitza la selecció de la taula.
     */
    private void initTableSelection() {
        tblSuppliers.getSelectionModel().addListSelectionListener(evt -> {
            if (!evt.getValueIsAdjusting()) {
                loadSelectedSupplier();
            }
        });
    }

    /**
     * Carrega el proveïdor seleccionat al formulari.
     */
    private void loadSelectedSupplier() {
        int selectedRow = tblSuppliers.getSelectedRow();

        if (selectedRow == -1) {
            selectedOriginalName = null;
            btnDelete.setEnabled(false);
            btnSave.setText("Crea");
            return;
        }

        int modelRow = tblSuppliers.convertRowIndexToModel(selectedRow);

        Object nameValue = tableModel.getValueAt(modelRow, 1);
        Object poblacioValue = tableModel.getValueAt(modelRow, 2);
        Object emailValue = tableModel.getValueAt(modelRow, 3);
        Object telefonValue = tableModel.getValueAt(modelRow, 4);

        selectedOriginalName = nameValue.toString();
        txtName.setText(selectedOriginalName);
        txtPassword.setText("");
        txtPoblacio.setText(poblacioValue != null ? poblacioValue.toString() : "");
        txtEmail.setText(emailValue != null ? emailValue.toString() : "");
        txtTelefon.setText(telefonValue != null ? telefonValue.toString() : "");

        btnDelete.setEnabled(true);
        btnSave.setText("Desa");
    }


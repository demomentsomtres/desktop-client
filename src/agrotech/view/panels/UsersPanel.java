    /**
     * Desa l'usuari actual, ja sigui creant-lo o modificant-lo.
     *
     * @param evt esdeveniment del botó
     */
    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String username = txtUsername.getText();
        String password = new String(txtPassword.getPassword());
        String roleText = (String) cmbRole.getSelectedItem();

        Role role = null;

        if (roleText != null && !roleText.isBlank()) {
            role = Role.valueOf(roleText);
        }

        ClientResponse<Void> response = usersService.saveUser(
                selectedOriginalUsername,
                username,
                password,
                role
        );

        if (response.isSuccess()) {
            JOptionPane.showMessageDialog(
                    this,
                    response.getMessage(),
                    "Informació",
                    JOptionPane.INFORMATION_MESSAGE
            );

            loadUsers();
            clearForm();
            return;
        }

        JOptionPane.showMessageDialog(
                this,
                response.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE
        );
    }//GEN-LAST:event_btnSaveActionPerformed

    /**
     * Elimina l'usuari seleccionat després de confirmar l'acció.
     *
     * @param evt esdeveniment del botó
     */
    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String usernameToDelete = selectedOriginalUsername;

        if (usernameToDelete == null || usernameToDelete.isBlank()) {
            usernameToDelete = txtUsername.getText().trim();
        }

        if (usernameToDelete.isBlank()) {
            JOptionPane.showMessageDialog(
                    this,
                    "Cal seleccionar un usuari.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        int option = JOptionPane.showConfirmDialog(
                this,
                "Vols eliminar l'usuari \"" + usernameToDelete + "\"?",
                "Confirmació",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE
        );

        if (option != JOptionPane.YES_OPTION) {
            return;
        }

        ClientResponse<Void> response = usersService.deleteUser(usernameToDelete);

        if (response.isSuccess()) {
            JOptionPane.showMessageDialog(
                    this,
                    response.getMessage(),
                    "Informació",
                    JOptionPane.INFORMATION_MESSAGE
            );

            loadUsers();
            clearForm();
            return;
        }

        JOptionPane.showMessageDialog(
                this,
                response.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE
        );
    }//GEN-LAST:event_btnDeleteActionPerformed


    /**
     * Neteja el formulari i reinicia la selecció.
     */
    private void clearForm() {
        selectedOriginalUsername = null;
        txtUsername.setText("");
        txtPassword.setText("");
        cmbRole.setSelectedIndex(-1);
        tblUsers.clearSelection();
        btnDelete.setEnabled(false);
        btnSave.setText("Crea");
        txtUsername.requestFocus();
    }

    /**
     * Cerca un usuari pel seu nom d'usuari i el mostra a la taula.
     */
    private void searchUser() {
        String username = txtSearchUsername.getText();

        ClientResponse<ManagedUser> response = usersService.getUserByUsername(username);

        if (!response.isSuccess()) {
            JOptionPane.showMessageDialog(
                    this,
                    response.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        ManagedUser user = response.getData();

        if (user == null) {
            JOptionPane.showMessageDialog(
                    this,
                    "No s'ha trobat cap usuari amb aquest nom.",
                    "Avís",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        tableModel.setRowCount(0);

        tableModel.addRow(new Object[]{
            user.getId(),
            user.getUsername(),
            user.getRole()
        });

        if (tableModel.getRowCount() > 0) {
            tblUsers.setRowSelectionInterval(0, 0);
        }
    }

    /**
     * Neteja la cerca i recarrega tots els usuaris.
     */
    private void clearSearch() {
        txtSearchUsername.setText("");
        loadUsers();
        clearForm();
    }

    /**
     * Carrega la llista d'usuaris a la taula.
     */
    private void loadUsers() {
        ClientResponse<List<ManagedUser>> response = usersService.getAllUsers();

        if (!response.isSuccess()) {
            JOptionPane.showMessageDialog(
                    this,
                    response.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        tableModel.setRowCount(0);

        for (ManagedUser user : response.getData()) {
            tableModel.addRow(new Object[]{
                user.getId(),
                user.getUsername(),
                user.getRole()
            });
        }
    }

    /**
     * Inicialitza la selecció de la taula.
     */
    private void initTableSelection() {
        tblUsers.getSelectionModel().addListSelectionListener(evt -> {
            if (!evt.getValueIsAdjusting()) {
                loadSelectedUser();
            }
        });
    }

    /**
     * Carrega l'usuari seleccionat al formulari.
     */
    private void loadSelectedUser() {
        int selectedRow = tblUsers.getSelectedRow();

        if (selectedRow == -1) {
            clearForm();
            return;
        }

        int modelRow = tblUsers.convertRowIndexToModel(selectedRow);

        Object usernameValue = tableModel.getValueAt(modelRow, 1);
        Object roleValue = tableModel.getValueAt(modelRow, 2);

        selectedOriginalUsername = usernameValue.toString();
        txtUsername.setText(selectedOriginalUsername);
        txtPassword.setText("");
        cmbRole.setSelectedItem(roleValue.toString());
        btnDelete.setEnabled(true);
        btnSave.setText("Desa");
    }


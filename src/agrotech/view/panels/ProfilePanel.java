    /**
     * Gestiona el botó "Desa els canvis".
     *
     * @param evt esdeveniment del botó
     */
    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String username = txtUsername.getText().trim();
        String newPassword = new String(txtNewPassword.getPassword()).trim();
        String confirmPassword = new String(txtConfirmPassword.getPassword()).trim();

        if (!newPassword.isEmpty() && !newPassword.equals(confirmPassword)) {
            JOptionPane.showMessageDialog(
                    this,
                    "Les contrasenyes no coincideixen.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        String usernameToSend = username.isEmpty() ? null : username;
        String passwordToSend = newPassword.isEmpty() ? null : newPassword;

        UsersService usersService = new UsersService();
        ClientResponse<Void> response = usersService.updateMyUser(usernameToSend, passwordToSend);

        if (!response.isSuccess()) {
            JOptionPane.showMessageDialog(
                    this,
                    response.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        JOptionPane.showMessageDialog(
                this,
                "Perfil actualitzat correctament.",
                "Èxit",
                JOptionPane.INFORMATION_MESSAGE
        );

        txtNewPassword.setText("");
        txtConfirmPassword.setText("");

        if (usernameToSend != null) {
            SessionManager.getCurrentUser().setUsername(usernameToSend);
            lblUsernameValue.setText(usernameToSend);
            String newInitials = usernameToSend.length() >= 2
                    ? usernameToSend.substring(0, 2).toUpperCase()
                    : usernameToSend.toUpperCase();
            lblAvatar.setText(newInitials);
        }
    }//GEN-LAST:event_btnSaveActionPerformed



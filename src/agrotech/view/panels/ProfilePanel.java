    /**
     * Configura la vista segons el rol de l'usuari loguejat.
     */
    private void configureViewByRole() {
        Role role = SessionManager.getCurrentUser().getRole();
        String username = SessionManager.getCurrentUser().getUsername();

        String initials = username.length() >= 2
                ? username.substring(0, 2).toUpperCase()
                : username.toUpperCase();
        lblAvatar.setText(initials);
        lblUsernameValue.setText(username);
        lblRoleBadge.setText(role.toString());

        if (role == Role.SUPPLIER) {
            lblRoleBadge.setBackground(new java.awt.Color(234, 243, 222));
            lblRoleBadge.setForeground(new java.awt.Color(59, 109, 17));
            lblAvatar.setBackground(new java.awt.Color(234, 243, 222));
            lblAvatar.setForeground(new java.awt.Color(59, 109, 17));
            pnlEditableForm.setVisible(false);
            pnlReadOnlyForm.setVisible(true);
            loadSupplierData();
        } else {
            lblRoleBadge.setBackground(new java.awt.Color(230, 241, 251));
            lblRoleBadge.setForeground(new java.awt.Color(24, 95, 165));
            lblAvatar.setBackground(new java.awt.Color(230, 241, 251));
            lblAvatar.setForeground(new java.awt.Color(24, 95, 165));
            pnlEditableForm.setVisible(true);
            pnlReadOnlyForm.setVisible(false);
            loadUserData();
        }
    }

    /**
     * Carrega les dades de l'usuari autenticat (ADMIN o CUSTOMER).
     */
    private void loadUserData() {
        Role role = SessionManager.getCurrentUser().getRole();

        if (role == Role.ADMIN) {
            UsersService usersService = new UsersService();
            ClientResponse<ManagedUser> response = usersService.getMyUser();

            if (!response.isSuccess()) {
                txtUsername.setText(SessionManager.getCurrentUser().getUsername());
                return;
            }
            txtUsername.setText(response.getData().getUsername());
        } else {
            txtUsername.setText(SessionManager.getCurrentUser().getUsername());
        }
    }

    /**
     * Carrega les dades del proveïdor autenticat (SUPPLIER).
     */
    private void loadSupplierData() {
        SuppliersService suppliersService = new SuppliersService();
        ClientResponse<ManagedSupplier> response = suppliersService.getMySupplier();

        if (!response.isSuccess()) {
            JOptionPane.showMessageDialog(
                    this,
                    response.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        txtPoblacio.setText(response.getData().getPoblacio() != null
                ? response.getData().getPoblacio() : "");
        txtEmail.setText(response.getData().getEmail() != null
                ? response.getData().getEmail() : "");
        txtTelefon.setText(response.getData().getTelefon() != null
                ? response.getData().getTelefon() : "");
        txtPoblacio.setEnabled(false);
        txtEmail.setEnabled(false);
        txtTelefon.setEnabled(false);
    }


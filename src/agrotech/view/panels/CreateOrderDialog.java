    /**
     * Afegeix el producte seleccionat al carro.
     *
     * @param evt esdeveniment del botó
     */
    private void btnAddToCartActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddToCartActionPerformed
        int selectedRow = tblProducts.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Cal seleccionar un producte.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        int modelRow = tblProducts.convertRowIndexToModel(selectedRow);
        ManagedProduct product = availableProducts.get(modelRow);

        int quantity;
        try {
            quantity = Integer.parseInt(txtQuantity.getText().trim());
            if (quantity <= 0) {
                throw new NumberFormatException();
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "La quantitat ha de ser un número positiu.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        int quantitatAlCarro = getQuantitatAlCarro(product.getId());
        int estocDisponible = product.getStock() - quantitatAlCarro;

        if (quantity > estocDisponible) {
            JOptionPane.showMessageDialog(
                    this,
                    "No hi ha prou estoc. Estoc disponible: " + estocDisponible,
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        double lineDiscount = calculateLineDiscount(product, quantity);
        double lineTotal = calculateLineTotal(product, quantity);

        cartLines.add(new OrderLineRequestDto(product.getId(), quantity));
        cartTableModel.addRow(new Object[]{
            product.getProductCategory(),
            quantity,
            formatMoney(product.getPrice()),
            formatMoney(lineDiscount),
            formatMoney(lineTotal)
        });

        updateTotal();
        updateProductsStock();
    }//GEN-LAST:event_btnAddToCartActionPerformed

    /**
     * Calcula la quantitat d'un producte que ja hi ha al carro.
     *
     * @param productId identificador del producte
     * @return quantitat total al carro
     */
    private int getQuantitatAlCarro(Long productId) {
        int total = 0;

        for (OrderLineRequestDto line : cartLines) {
            if (line.getProductId().equals(productId)) {
                total += line.getQuantity();
            }
        }

        return total;
    }

    /**
     * Elimina la línia seleccionada del carro.
     *
     * @param evt esdeveniment del botó
     */
    private void btnRemoveLineActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoveLineActionPerformed
        int selectedRow = tblCart.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Cal seleccionar una línia del carro.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        int modelRow = tblCart.convertRowIndexToModel(selectedRow);

        cartLines.remove(modelRow);
        cartTableModel.removeRow(modelRow);

        updateTotal();
        updateProductsStock();
    }//GEN-LAST:event_btnRemoveLineActionPerformed

    /**
     * Confirma la comanda i la envia al backend.
     *
     * @param evt esdeveniment del botó
     */
    private void btnConfirmActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmActionPerformed
        String poblacio = txtPoblacio.getText().trim();

        if (poblacio.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this,
                    "Cal indicar la població de destí.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        if (cartLines.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this,
                    "Cal afegir com a mínim un producte al carro.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        ClientResponse<ManagedOrder> response
                = ordersService.createOrder(poblacio, cartLines);

        if (response.isSuccess()) {
            ManagedOrder createdOrder = response.getData();

            String message = "Comanda creada correctament!";

            if (createdOrder != null) {
                message += "\nTotal s/IVA: "
                        + formatMoney(createdOrder.getTotalOrderPrice());

                message += "\nIVA: "
                        + formatMoney(createdOrder.getTotalOrderTax());

                message += "\nTotal amb IVA: "
                        + formatMoney(calculateCustomerTotal(createdOrder));

                message += "\nDescompte aplicat: "
                        + formatMoney(createdOrder.getTotalDiscount());
            }

            JOptionPane.showMessageDialog(
                    this,
                    message,
                    "Informació",
                    JOptionPane.INFORMATION_MESSAGE
            );

            orderConfirmed = true;
            dispose();
            return;
        }

        JOptionPane.showMessageDialog(
                this,
                response.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE
        );
    }//GEN-LAST:event_btnConfirmActionPerformed


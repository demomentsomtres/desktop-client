    /**
     * Carrega els productes disponibles a la taula.
     */
    private void loadProducts() {
        ClientResponse<List<ManagedProduct>> response = productsService.getAvailableProducts();

        if (!response.isSuccess()) {
            JOptionPane.showMessageDialog(
                    this,
                    response.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        availableProducts = response.getData();
        productsTableModel.setRowCount(0);

        for (ManagedProduct product : availableProducts) {
            productsTableModel.addRow(new Object[]{
                product.getId(),
                product.getProductCategory(),
                formatMoney(product.getPrice()),
                product.getStock(),
                product.getExpirationDate(),
                getDiscountText(product)
            });
        }
    }

